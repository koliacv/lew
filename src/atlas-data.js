export function selectAtlas(question) {
  const text = [question.q, question.opts?.[0], ...(question.steps || [])].filter(Boolean).join(" ");
  const priority = ["pregnancy", "spine", "skin", "kidney", "endocrine", "female", "digestive", "heart", "lungs", "blood", "lymphatic", "joint", "brain"];
  return priority.map(id => ATLAS.find(a => a.id === id)).find(a => new RegExp(a.pattern, "iu").test(text)) || null;
}
